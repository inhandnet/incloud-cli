func NewCmdPolicy(f *factory.Factory) *cobra.Command {
	cmd := &cobra.Command{
		Use:   "policy",
		Short: "Manage report policies",
		Long:  "Create, list, update and delete the policies that generate reports.",
	}

	cmd.AddCommand(NewCmdPolicyList(f))
	cmd.AddCommand(NewCmdPolicyGet(f))
	cmd.AddCommand(NewCmdPolicyCreate(f))
	cmd.AddCommand(NewCmdPolicyUpdate(f))
	cmd.AddCommand(NewCmdPolicyDelete(f))
	cmd.AddCommand(NewCmdPolicyTemplates(f))

	return cmd
}

type policyListOptions struct {
	cmdutil.ListFlags
	Name string
}

// applyTo is not shown but must be fetched: the API fails when it is projected away.
var defaultPolicyListFields = []string{"_id", "name", "applyTo", "schedule", "timezone", "period", "format", "templates", "recipient", "nextScheduledTime"}

var policyListColumns = []string{"_id", "name", "frequency", "at", "timezone", "period", "format", "templateCount", "recipient", "nextScheduledTime"}

func NewCmdPolicyList(f *factory.Factory) *cobra.Command {
	opts := &policyListOptions{}

	cmd := &cobra.Command{
		Use:     "list",
		Short:   "List scheduled report policies",
		Long:    "List scheduled report policies with pagination. One-off policies are not listed; their reports appear in 'incloud report list'.",
		Aliases: []string{"ls"},
		Example: `  # List report policies
  incloud report policy list

  # Filter by name
  incloud report policy list --name weekly`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			client, err := f.APIClient()
			if err != nil {
				return err
			}

			q := cmdutil.NewQuery(cmd, defaultPolicyListFields)
			if opts.Name != "" {
				q.Set("name", opts.Name)
			}

			body, err := client.Get(policiesPath, q)
			if err != nil {
				return err
			}

			output, _ := cmd.Flags().GetString("output")
			return iostreams.FormatOutput(body, f.IO, output,
				iostreams.WithTransform(policyTableRows),
				iostreams.WithColumns(policyListColumns...),
			)
		},
	}

	opts.Register(cmd)
	cmd.Flags().StringVar(&opts.Name, "name", "", "Filter by policy name (fuzzy match)")

	return cmd
}

// policyTableRows replaces each policy's schedule object with a readable
// frequency and HH:MM time for table output, and shows the template count.
func policyTableRows(body []byte) ([]byte, error) {
	var resp struct {
		Result []map[string]any `json:"result"`
	}
	if err := json.Unmarshal(body, &resp); err != nil {
		return nil, fmt.Errorf("parsing response: %w", err)
	}

	rows := resp.Result
	for _, p := range rows {
		if s, ok := p["schedule"].(map[string]any); ok {
			p["frequency"] = describeFrequency(s)
			h, _ := s["hourOfDay"].(float64)
			m, _ := s["minuteOfHour"].(float64)
			p["at"] = fmt.Sprintf("%02d:%02d", int(h), int(m))
			delete(p, "schedule")
		}
		if t, ok := p["templates"].([]any); ok {
			p["templateCount"] = len(t)
			delete(p, "templates")
		}
	}
	if rows == nil {
		rows = []map[string]any{}
	}
	return json.Marshal(rows)
}

func describeFrequency(s map[string]any) string {
	if d, ok := s["dayOfMonth"].(float64); ok {
		return fmt.Sprintf("monthly (day %d)", int(d))
	}
	if d, ok := s["dayOfWeek"].(float64); ok && int(d) >= 1 && int(d) <= 7 {
		return "weekly (" + weekdayNames[int(d)-1] + ")"
	}
	return "daily"
}

func NewCmdPolicyGet(f *factory.Factory) *cobra.Command {
	cmd := &cobra.Command{
		Use:   "get <policy-id>",
		Short: "Get report policy details",
		Example: `  # Get policy details
  incloud report policy get 507f1f77bcf86cd799439011`,
		Args: cmdutil.ObjectIDArgs(cobra.ExactArgs(1), 0, "report policy id", "incloud report policy list --name %s"),
		RunE: func(cmd *cobra.Command, args []string) error {
			client, err := f.APIClient()
			if err != nil {
				return err
			}

			body, err := client.Get(policiesPath+"/"+args[0], nil)
			if err != nil {
				return err
			}

			output, _ := cmd.Flags().GetString("output")
			return iostreams.FormatOutput(body, f.IO, output)
		},
	}
	return cmd
}

func NewCmdPolicyDelete(f *factory.Factory) *cobra.Command {
	var yes bool

	cmd := &cobra.Command{
		Use:     "delete <policy-id> [<policy-id>...]",
		Short:   "Delete report policies",
		Long:    "Delete report policies. Reports already generated by them are kept.",
		Aliases: []string{"rm"},
		Example: `  # Delete a policy (will prompt for confirmation)
  incloud report policy delete 507f1f77bcf86cd799439011

  # Skip confirmation
  incloud report policy delete 507f1f77bcf86cd799439011 --yes`,
		Args: cmdutil.ObjectIDArgsAll(cobra.MinimumNArgs(1), "report policy id", "incloud report policy list --name %s"),
		RunE: func(cmd *cobra.Command, args []string) error {
			return deleteByIDs(f, args, yes, policiesPath, "report policy")
		},
	}

	cmd.Flags().BoolVarP(&yes, "yes", "y", false, "Skip confirmation prompt")

	return cmd
}
